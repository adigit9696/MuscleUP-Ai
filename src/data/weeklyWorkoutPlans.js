export function createWeeklyPlanFromTemplate(templateId = 'balanced') {
  const tpl = PLAN_TEMPLATES[templateId] || PLAN_TEMPLATES.balanced;
  return {
    templateId: tpl.id,
    label: tpl.label,
    tagline: tpl.tagline,
    createdAt: new Date().toISOString(),
    days: tpl.days.map((d) => ({
      ...d,
      tasks: d.tasks.map((t) => ({ ...t, completed: false, claimed: false })),
    })),
  };
}

// Helper: returns 'mon' | 'tue' | ... | 'sun' for today's local day of week
export function getTodayDayId() {
  const map = ['sun', 'mon', 'tue', 'wed', 'thu', 'fri', 'sat'];
  return map[new Date().getDay()];
}
